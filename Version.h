//  1) поднять номер в FIRMWARE_VERSION по правилам ниже;
//  2) закоммитить;
//  3) поставить git-тег с тем же номером: git tag -a v3.0.0 -m "..."
//     (тег и число в FIRMWARE_VERSION должны совпадать, иначе по
//     строке Firmware в веб-интерфейсе нельзя будет понять, что залито в лампу).
// ==================================================================

